import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import test from 'node:test'

import { apply, resolveOptions } from '../lib/index.js'

const gitAi = findGitAi()

test('end to end: file edits and shell commands become AI authorship', { skip: !gitAi }, async () => {
  const repo = await createRepo()
  try {
    const harness = createHarness({ binary: gitAi, agentName: 'dsh-test' })

    const agent = createAgent(repo)
    const exec = {
      name: 'write',
      callId: 'call-file-1',
      arguments: { file_path: 'src/ai.txt' },
      agent,
      signal: new AbortController().signal,
    }

    // Pre-tool: baseline checkpoint must not change the pipeline decision.
    const decision = await harness.emit('tools/pre-execute', exec, () => ({ kind: 'allow' }))
    assert.deepEqual(decision, { kind: 'allow' })

    await mkdir(join(repo, 'src'), { recursive: true })
    await writeFile(join(repo, 'src', 'ai.txt'), 'written by the model\n', 'utf8')

    const post = await harness.emit(
      'tools/post-execute',
      exec,
      { isError: false, value: { path: join(repo, 'src', 'ai.txt') } },
      () => ({ kind: 'accept' }),
    )
    assert.deepEqual(post, { kind: 'accept' })

    const stats = await waitForAiAuthorship(repo, 1)
    assert.equal(stats.ai_additions, 1, JSON.stringify(stats))
    const status = await gitAiStatus(repo)
    assert.equal(status.checkpoints?.[0]?.tool_model, 'dsh-test test-model', JSON.stringify(status))
  } finally {
    await cleanup(repo)
  }
})

test('end to end: shell commands attribute their file changes', { skip: !gitAi }, async () => {
  const repo = await createRepo()
  try {
    const harness = createHarness({ binary: gitAi, agentName: 'dsh-test' })
    const agent = createAgent(repo)
    const exec = {
      name: 'pwsh',
      callId: 'call-shell-1',
      arguments: { command: 'node build.js' },
      agent,
      signal: new AbortController().signal,
    }

    assert.deepEqual(await harness.emit('tools/pre-execute', exec, () => ({ kind: 'allow' })), { kind: 'allow' })
    await writeFile(join(repo, 'built.txt'), 'generated by a command\n', 'utf8')
    assert.deepEqual(
      await harness.emit('tools/post-execute', exec, { isError: false, value: {} }, () => ({ kind: 'accept' })),
      { kind: 'accept' },
    )

    const stats = await waitForAiAuthorship(repo, 1)
    assert.ok(stats.ai_additions >= 1, JSON.stringify(stats))
  } finally {
    await cleanup(repo)
  }
})

test('end to end: failed tools and non-git directories stay untouched', { skip: !gitAi }, async () => {
  const repo = await createRepo()
  const outside = await mkdtemp(join(tmpdir(), 'dsh-git-ai-outside-'))
  try {
    const harness = createHarness({ binary: gitAi, agentName: 'dsh-test' })

    const failed = {
      name: 'write',
      callId: 'call-failed',
      arguments: { file_path: 'failed.txt' },
      agent: createAgent(repo),
      signal: new AbortController().signal,
    }
    await harness.emit('tools/post-execute', failed, { isError: true, error: { message: 'boom' } }, () => ({ kind: 'accept' }))

    const outsideExec = {
      name: 'write',
      callId: 'call-outside',
      arguments: { file_path: 'x.txt' },
      agent: createAgent(outside),
      signal: new AbortController().signal,
    }
    assert.deepEqual(await harness.emit('tools/pre-execute', outsideExec, () => ({ kind: 'allow' })), { kind: 'allow' })
    await writeFile(join(outside, 'x.txt'), 'outside\n', 'utf8')
    assert.deepEqual(
      await harness.emit('tools/post-execute', outsideExec, { isError: false, value: { path: join(outside, 'x.txt') } }, () => ({ kind: 'accept' })),
      { kind: 'accept' },
    )

    const status = await gitAiStatus(repo)
    assert.equal(status.stats.ai_additions, 0, JSON.stringify(status))
  } finally {
    await cleanup(repo)
    await cleanup(outside)
  }
})

test('a missing git-ai binary never blocks or fails a tool call', async () => {
  const script = `
    import { apply } from ${JSON.stringify(new URL('../lib/index.js', import.meta.url).href)}
    const handlers = new Map()
    const ctx = {
      on: (event, listener) => { handlers.set(event, listener); return () => {} },
      logger: { info: () => {} },
      get: () => undefined,
    }
    apply(ctx, { binary: 'git-ai-definitely-not-installed', diagnostics: false })
    const agent = {
      session: { id: 's', header: { cwd: process.cwd() }, requestHeader: () => ({ config: { model: 'm' } }) },
      ctx: { get: () => undefined },
    }
    const exec = { name: 'write', callId: 'c', arguments: { file_path: 'a.txt' }, agent }
    const pre = await handlers.get('tools/pre-execute')(exec, () => ({ kind: 'allow' }))
    const post = await handlers.get('tools/post-execute')(exec, { isError: false, value: {} }, () => ({ kind: 'accept' }))
    if (pre.kind !== 'allow' || post.kind !== 'accept') throw new Error('pipeline decision changed')
    process.stdout.write('ok')
  `
  const result = spawnSync(process.execPath, ['--input-type=module', '-e', script], {
    cwd: process.cwd(),
    encoding: 'utf8',
    timeout: 60000,
  })
  assert.equal(result.status, 0, result.stderr)
  assert.equal(result.stdout.trim(), 'ok')
})

/**
 * Build a harness that captures the plugin's pipeline listeners.
 * @param {Record<string, unknown>} config plugin config.
 * @returns {{emit: (event: string, ...args: unknown[]) => Promise<any>}} captured listeners.
 */
function createHarness(config) {
  const handlers = new Map()
  const ctx = {
    on: (event, listener) => {
      handlers.set(event, listener)
      return () => handlers.delete(event)
    },
    logger: { info: () => {} },
    get: () => undefined,
  }
  apply(ctx, resolveOptions({ ...config, diagnostics: false }))
  return {
    emit: async (event, ...args) => {
      const listener = handlers.get(event)
      assert.ok(listener, `missing listener for ${event}`)
      return listener(...args)
    },
  }
}

/**
 * Fake Agent whose session reports the repository as working directory.
 * @param {string} cwd session directory.
 * @returns {Record<string, any>} fake agent.
 */
function createAgent(cwd) {
  return {
    session: {
      id: 'session-test',
      header: { cwd },
      requestHeader: () => ({ config: { provider: 'deepseek-official', model: 'test-model' } }),
      deriveMessages: () => [
        { role: 'user', source: { kind: 'user' }, content: [{ type: 'text', text: 'Implement the feature' }] },
        { role: 'assistant', content: [{ type: 'text', text: 'Implementing it now' }] },
      ],
    },
    ctx: {
      get: (key) => (key === 'workingDirectory' ? { ensure: async () => cwd } : undefined),
    },
  }
}

/**
 * Remove a temporary directory, tolerating Windows file locks from Git AI.
 * @param {string} directory path to remove.
 * @returns {Promise<void>} resolves once the directory is gone.
 */
async function cleanup(directory) {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    try {
      await rm(directory, { recursive: true, force: true })
      return
    } catch {
      await new Promise((resolve) => setTimeout(resolve, 300))
    }
  }
}

/**
 * Create a temporary Git repository with an initial commit.
 * @returns {Promise<string>} repository path.
 */
async function createRepo() {
  const repo = await mkdtemp(join(tmpdir(), 'dsh-git-ai-'))
  git(repo, ['init', '-q'])
  git(repo, ['config', 'user.email', 'test@example.com'])
  git(repo, ['config', 'user.name', 'Test'])
  await writeFile(join(repo, 'README.md'), 'initial\n', 'utf8')
  git(repo, ['add', '.'])
  git(repo, ['commit', '-qm', 'init'])
  return repo
}

/**
 * Run a Git command in a repository.
 * @param {string} cwd repository.
 * @param {string[]} args arguments.
 * @returns {void}
 */
function git(cwd, args) {
  execFileSync('git', args, { cwd, stdio: 'ignore' })
}

/**
 * Read `git-ai status --json` for a repository.
 * @param {string} repo repository path.
 * @returns {Promise<any>} parsed status.
 */
async function gitAiStatus(repo) {
  const result = spawnSync(gitAi, ['status', '--json'], { cwd: repo, encoding: 'utf8', timeout: 30000 })
  assert.equal(result.status, 0, result.stderr)
  return JSON.parse(result.stdout)
}

/**
 * Poll Git AI until the expected amount of AI authorship appears.
 * @param {string} repo repository.
 * @param {number} minimum expected AI additions.
 * @returns {Promise<any>} status containing the authorship.
 */
async function waitForAiAuthorship(repo, minimum) {
  const deadline = Date.now() + 15000
  let last
  while (Date.now() < deadline) {
    last = await gitAiStatus(repo)
    if ((last.stats?.ai_additions ?? 0) >= minimum) return last.stats
    await new Promise((resolve) => setTimeout(resolve, 250))
  }
  assert.fail(`no AI authorship within timeout: ${JSON.stringify(last)}`)
}

/**
 * Locate a working `git-ai` binary.
 * @returns {string | undefined} absolute binary path.
 */
function findGitAi() {
  for (const candidate of ['git-ai', join(process.env.USERPROFILE ?? '', '.git-ai', 'bin', 'git-ai.exe')]) {
    if (!candidate) continue
    if (candidate.includes('\\') && !existsSync(candidate)) continue
    const probe = spawnSync(candidate, ['--version'], { encoding: 'utf8', timeout: 15000 })
    if (probe.status === 0) return candidate
  }
  return undefined
}


